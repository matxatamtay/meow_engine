fn rows(a: &str, b: &str, c: &str, d: &str, e: &str, f: &str, g: &str) -> [u8; 7] {
    [a, b, c, d, e, f, g].map(bits)
}

fn bits(source: &str) -> u8 {
    source
        .bytes()
        .fold(0, |value, byte| (value << 1) | u8::from(byte == b'1'))
}

